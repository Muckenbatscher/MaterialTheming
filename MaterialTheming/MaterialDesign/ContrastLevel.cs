namespace MaterialTheming
{
    /// <summary>
    /// The available known contrast levels.
    /// </summary>
    public enum ContrastLevel
    {
        /// <summary>
        /// A normal contrast level.<br/>The corresponding contrast level value is <c>0.0</c>.
        /// </summary>
        Normal,
        /// <summary>
        /// A medium contrast level.<br/>The corresponding contrast level value is <c>0.5</c>.
        /// </summary>
        Medium,
        /// <summary>
        /// A high contrast level.<br/>The corresponding contrast level value is <c>1.0</c>.
        /// </summary>
        High
    }
}
